/**
 * Given a verse_id (e.g. "JHN.1.1") and a direction, returns the adjacent verse_id.
 * Returns null at absolute boundaries (before GEN.1.1 or after REV.22.21).
 */
export function getAdjacentVerseId(
  verseId: string,
  direction: "prev" | "next"
): string | null {
  const parts = verseId.split(".");
  if (parts.length !== 3) return null;

  const book = parts[0];
  const chapter = parseInt(parts[1], 10);
  const verse = parseInt(parts[2], 10);

  const bookIdx = BOOK_ORDER.indexOf(book);
  if (bookIdx === -1) return null;

  const counts = VERSE_COUNTS[book];
  if (!counts) return null;

  if (direction === "next") {
    const maxVerse = counts[chapter];
    if (verse < maxVerse) {
      return `${book}.${chapter}.${verse + 1}`;
    }
    // Last verse of chapter — go to next chapter
    const maxChapter = counts.length - 1;
    if (chapter < maxChapter) {
      return `${book}.${chapter + 1}.1`;
    }
    // Last chapter of book — go to next book
    if (bookIdx < BOOK_ORDER.length - 1) {
      const nextBook = BOOK_ORDER[bookIdx + 1];
      return `${nextBook}.1.1`;
    }
    return null; // REV last verse
  } else {
    // prev
    if (verse > 1) {
      return `${book}.${chapter}.${verse - 1}`;
    }
    // First verse of chapter — go to last verse of previous chapter
    if (chapter > 1) {
      const prevChapterVerses = counts[chapter - 1];
      return `${book}.${chapter - 1}.${prevChapterVerses}`;
    }
    // First chapter of book — go to last verse of previous book
    if (bookIdx > 0) {
      const prevBook = BOOK_ORDER[bookIdx - 1];
      const prevCounts = VERSE_COUNTS[prevBook];
      const lastChapter = prevCounts.length - 1;
      const lastVerse = prevCounts[lastChapter];
      return `${prevBook}.${lastChapter}.${lastVerse}`;
    }
    return null; // GEN.1.1
  }
}
